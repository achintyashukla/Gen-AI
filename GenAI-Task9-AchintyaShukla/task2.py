# Task 2: Important Mathematical Operations

import numpy as np

A = np.array([10, 20, 30, 40])
B = np.array([1, 2, 3, 4])

print(f"Array A: {A}")
print(f"Array B: {B}\n")

# 1. Addition (A + B)
print(f"Addition (A + B): {A + B}")
# Extra: using np.add()
print(f"Using np.add(A, B): {np.add(A, B)}\n")

# 2. Subtraction (A - B)
print(f"Subtraction (A - B): {A - B}")
# Extra: using np.subtract()
print(f"Using np.subtract(A, B): {np.subtract(A, B)}\n")

# 3. Multiplication (A * B)
print(f"Multiplication (A * B): {A * B}\n")

# 4. Division (A / B)
print(f"Division (A / B): {A / B}\n")

# 5. Power (A ** 2)
print(f"Power (A ** 2): {A ** 2}")
